cd libvncserver

rm -rf build
mkdir build

cd build


# CFLAGS=${CFLAGS} prefix=${PREFIX} ../configure --static


cmake -D ENABLE_SHARED=0 -DCMAKE_PREFIX_PATH=${PREFIX} -DCMAKE_INSTALL_PREFIX=${PREFIX} -DCMAKE_C_FLAGS="${CFLAGS}" \
-DBUILD_SHARED_LIBS=OFF -DWITH_ZLIB=ON -DWITH_LZO=OFF -DWITH_JPEG=ON -DWITH_PNG=OFF -DWITH_SDL=OFF -DWITH_GTK=OFF -DWITH_LIBSSHTUNNEL=OFF -DWITH_THREADS=OFF \
-DPREFER_WIN32THREADS=OFF -DWITH_GNUTLS=OFF -DWITH_OPENSSL=ON -DWITH_SYSTEMD=OFF -DWITH_GCRYPT=OFF -DWITH_FFMPEG=OFF -DWITH_TIGHTVNC_FILETRANSFER=OFF \
-DWITH_24BPP=ON -DWITH_IPv6=ON -DWITH_WEBSOCKETS=OFF -DWITH_SASL=OFF -DWITH_XCB=OFF -DWITH_EXAMPLES=OFF -DWITH_TESTS=OFF \
..

make
make install